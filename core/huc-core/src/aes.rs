const RCON: [u8; 15] = [0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,0x6c,0xd8,0xab,0x4d];

pub struct Aes256 { round_keys: [[u8; 16]; 15] }

impl Aes256 {
    pub fn new(key: &[u8; 32]) -> Self {
        let mut rk = [[0u8; 16]; 15];
        let mut w = [0u8; 240]; // 60 words * 4 bytes
        w[..32].copy_from_slice(key);
        for i in 8..60 {
            let mut t = [w[4*(i-1)], w[4*(i-1)+1], w[4*(i-1)+2], w[4*(i-1)+3]];
            if i % 8 == 0 {
                // RotWord then SubWord; Rcon XORs the FIRST byte
                t = [SBOX[t[1] as usize] ^ RCON[i/8], SBOX[t[2] as usize], SBOX[t[3] as usize], SBOX[t[0] as usize]];
            } else if i % 8 == 4 {
                t = [SBOX[t[0] as usize], SBOX[t[1] as usize], SBOX[t[2] as usize], SBOX[t[3] as usize]];
            }
            for j in 0..4 { w[4*i+j] = w[4*(i-8)+j] ^ t[j]; }
        }
        for r in 0..15 { rk[r].copy_from_slice(&w[16*r..16*r+16]); }
        Aes256 { round_keys: rk }
    }

    pub fn encrypt_block(&self, block: &[u8; 16]) -> [u8; 16] {
        let mut s = [0u8; 16];
        for i in 0..16 { s[i] = block[i] ^ self.round_keys[0][i]; }
        for r in 1..14 {
            sub_bytes(&mut s);
            shift_rows(&mut s);
            mix_columns(&mut s);
            add_round_key(&mut s, &self.round_keys[r]);
        }
        sub_bytes(&mut s);
        shift_rows(&mut s);
        add_round_key(&mut s, &self.round_keys[14]);
        s
    }
}

fn sub_bytes(s: &mut [u8; 16]) { for b in s.iter_mut() { *b = SBOX[*b as usize]; } }

fn shift_rows(s: &mut [u8; 16]) {
    let t = *s;
    s[1]=t[5]; s[5]=t[9]; s[9]=t[13]; s[13]=t[1];
    s[2]=t[10]; s[6]=t[14]; s[10]=t[2]; s[14]=t[6];
    s[3]=t[15]; s[7]=t[3]; s[11]=t[7]; s[15]=t[11];
}

fn xtime(a: u8) -> u8 { if a & 0x80 != 0 { (a << 1) ^ 0x1b } else { a << 1 } }

fn mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = 4 * c;
        let (a0, a1, a2, a3) = (s[i], s[i+1], s[i+2], s[i+3]);
        s[i]   = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
        s[i+1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
        s[i+2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
        s[i+3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    }
}

fn add_round_key(s: &mut [u8; 16], rk: &[u8; 16]) {
    for i in 0..16 { s[i] ^= rk[i]; }
}

/// AES-256-CTR: keystream = AES(iv || counter); symmetric encrypt/decrypt.
pub fn aes256_ctr(key: &[u8; 32], iv: &[u8; 16], data: &[u8]) -> Vec<u8> {
    let aes = Aes256::new(key);
    let mut out = Vec::with_capacity(data.len());
    let mut counter = u128::from_be_bytes(*iv);
    for chunk in data.chunks(16) {
        let ks = aes.encrypt_block(&counter.to_be_bytes());
        for (i, &b) in chunk.iter().enumerate() { out.push(b ^ ks[i]); }
        counter = counter.wrapping_add(1);
    }
    out
}

/// Sealed envelope: iv || ciphertext || HMAC-SHA256(key_mac, iv || ct).
/// Two keys derived by domain separation so encryption and MAC keys differ.
pub fn seal(key: &[u8; 32], iv: &[u8; 16], plaintext: &[u8]) -> Vec<u8> {
    let mac_key = crate::hmac_sha256(key, b"huc-envelope-mac");
    let ct = aes256_ctr(key, iv, plaintext);
    let mut out = Vec::with_capacity(16 + ct.len() + 32);
    out.extend_from_slice(iv);
    out.extend_from_slice(&ct);
    out.extend_from_slice(&crate::hmac_sha256(&mac_key, &out));
    out
}

/// Open a sealed envelope. Constant-time tag verification; any tamper → None.
pub fn open(key: &[u8; 32], envelope: &[u8]) -> Option<Vec<u8>> {
    if envelope.len() < 16 + 32 { return None; }
    let (iv, rest) = envelope.split_at(16);
    let (ct, tag) = rest.split_at(rest.len() - 32);
    let mac_key = crate::hmac_sha256(key, b"huc-envelope-mac");
    let want = crate::hmac_sha256(&mac_key, &envelope[..envelope.len() - 32]);
    if !crate::ct_eq(tag, &want) { return None; }
    let mut ivb = [0u8; 16];
    ivb.copy_from_slice(iv);
    Some(aes256_ctr(key, &ivb, ct))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::hex;

    #[test]
    fn fips197_aes256_vector() {
        // FIPS-197 Appendix C.3
        let key: [u8; 32] = [
            0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
            0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f];
        let pt: [u8; 16] = [
            0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff];
        let aes = Aes256::new(&key);
        assert_eq!(hex(&aes.encrypt_block(&pt)), "8ea2b7ca516745bfeafc49904b496089");
    }

    #[test]
    fn sp800_38a_ctr_vector_first_block() {
        // NIST SP 800-38A F.5.5 (CTR-AES256), block 1
        let key: [u8; 32] = [
            0x60,0x3d,0xeb,0x10,0x15,0xca,0x71,0xbe,0x2b,0x73,0xae,0xf0,0x85,0x7d,0x77,0x81,
            0x1f,0x35,0x2c,0x07,0x3b,0x61,0x08,0xd7,0x2d,0x98,0x10,0xa3,0x09,0x14,0xdf,0xf4];
        let iv: [u8; 16] = [
            0xf0,0xf1,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,0xf8,0xf9,0xfa,0xfb,0xfc,0xfd,0xfe,0xff];
        let pt: [u8; 16] = [
            0x6b,0xc1,0xbe,0xe2,0x2e,0x40,0x9f,0x96,0xe9,0x3d,0x7e,0x11,0x73,0x93,0x17,0x2a];
        let ct = aes256_ctr(&key, &iv, &pt);
        assert_eq!(hex(&ct), "601ec313775789a5b7a7f504bbf3d228");
    }

    #[test]
    fn envelope_roundtrip_and_tamper() {
        let key = [0x42u8; 32];
        let iv = [0x01u8; 16];
        let env = seal(&key, &iv, b"patient message: sannu");
        assert_eq!(open(&key, &env).unwrap(), b"patient message: sannu");
        // tamper one ciphertext byte → open must fail (HMAC)
        let mut bad = env.clone();
        bad[20] ^= 0x01;
        assert!(open(&key, &bad).is_none());
        // wrong key → fail
        assert!(open(&[0x43u8; 32], &env).is_none());
    }
}
